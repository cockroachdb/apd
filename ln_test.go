func TestLnSeriesEnclosure(t *testing.T) {
	// Check the fixed-point enclosure against exact rational partial sums and
	// their geometric tail bounds, independently of Decimal arithmetic.
	for _, places := range []int64{9, 42, 136} {
		for _, denominator := range []int64{3, 9, 100, 1000000001} {
			t.Run(fmt.Sprintf("%d/%d", places, denominator), func(t *testing.T) {
				var scale BigInt
				scale.Exp(bigTen, NewBigInt(places), nil)
				lo, hi := lnSeriesBounds(bigOne, NewBigInt(denominator), &scale)
				y := big.NewRat(1, denominator)
				square := new(big.Rat).Mul(y, y)
				power := new(big.Rat).Set(y)
				sum := new(big.Rat)
				terms := 4*places + 10
				for n := int64(0); n < terms; n++ {
					term := new(big.Rat).Quo(power, big.NewRat(2*n+1, 1))
					sum.Add(sum, term)
					power.Mul(power, square)
				}
				sum.Mul(sum, big.NewRat(2, 1))
				tail := new(big.Rat).Quo(power, big.NewRat(2*terms+1, 1))
				tail.Mul(tail, big.NewRat(2, 1))
				tail.Quo(tail, new(big.Rat).Sub(big.NewRat(1, 1), square))
				upper := new(big.Rat).Add(sum, tail)
				toRat := func(v *BigInt) *big.Rat {
					r, ok := new(big.Rat).SetString(v.String() + "/" + scale.String())
					if !ok {
						t.Fatal("invalid rational")
					}
					return r
				}
				if toRat(&lo).Cmp(sum) > 0 || toRat(&hi).Cmp(upper) < 0 {
					t.Fatalf("fixed-point enclosure [%s,%s] misses rational enclosure [%s,%s]", &lo, &hi, sum, upper)
				}
			})
		}
	}
}

func TestLnPrecisionLimits(t *testing.T) {
	for _, p := range []uint32{0, uint32(MaxExponent)} {
		t.Run(fmt.Sprint(p), func(t *testing.T) {
			c := BaseContext.WithPrecision(p)
			c.Traps = 0
			var got Decimal
			if _, err := c.Ln(&got, decimalTwo); err == nil {
				t.Fatal("expected precision error")
			}
		})
	}
	c := BaseContext.WithPrecision(34)
	var got Decimal
	flags, err := c.Ln(&got, decimalOne)
	if err != nil || flags != 0 || !got.IsZero() {
		t.Fatalf("Ln(1) = %s, %s, %v", &got, flags, err)
	}
}

func TestLnRefinementLimit(t *testing.T) {
	// For u=10^-n, u-u*u/2 < ln(1+u) < u. At n=49960 the
	// first enclosure straddles u; doubling its scale overshoots the
	// supported maximum even though that maximum resolves the boundary.
	for _, tc := range []struct {
		name     string
		distance int
		belowOne bool
		mode     Rounder
		want     string
		wantErr  bool
	}{
		{"cap_clamped", 49960, false, RoundDown, "9.999999999999999999999999999999999E-49961", false},
		{"cap_clamped_later", 49970, false, RoundDown, "9.999999999999999999999999999999999E-49971", false},
		{"negative", 49960, true, RoundFloor, "-1.000000000000000000000000000000001E-49960", false},
		{"ceiling_control", 49960, false, RoundCeiling, "1E-49960", false},
		{"cap_exhausted", 50000, false, RoundDown, "", true},
		{"initial_at_cap", 99958, false, RoundDown, "", true},
		{"initial_above_cap", 99959, false, RoundDown, "", true},
	} {
		t.Run(tc.name, func(t *testing.T) {
			input := "1." + strings.Repeat("0", tc.distance-1) + "1"
			if tc.belowOne {
				input = "0." + strings.Repeat("9", tc.distance)
			}
			x, _, err := NewFromString(input)
			if err != nil {
				t.Fatal(err)
			}
			c := BaseContext.WithPrecision(34)
			c.Rounding = tc.mode
			c.Traps = 0
			var got Decimal
			flags, err := c.Ln(&got, x)
			if tc.wantErr {
				if err == nil || err.Error() != "ln: required working precision exceeds supported limit" {
					t.Fatalf("expected working-precision limit error, got %v", err)
				}
				return
			}
			if err != nil {
				t.Fatal(err)
			}
			want, _, err := NewFromString(tc.want)
			if err != nil {
				t.Fatal(err)
			}
			if got.Cmp(want) != 0 || flags != Inexact|Rounded {
				t.Fatalf("got %s, flags %s; want %s, inexact, rounded", &got, flags, want)
			}
		})
	}
}
